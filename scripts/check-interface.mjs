assert.ok(app.visibleVerificationNotes(hotspot).includes('The source says up to three months. Current official policy says three weeks; do not assume a three-month loan.'));
for(const r of data.resources)assert.ok(app.visibleVerificationNotes(r).every(note=>!note.startsWith('Only the fields named as checked')));
const appSource=fs.readFileSync(path.join(root,'dist/app.js'),'utf8');
assert.ok(!appSource.includes('Original research & source notes')&&!appSource.includes('<details class="source-details">'));
console.log('PASS Pertinent hotspot caveat is retained while provenance panels and repeated boilerplate are excluded from the UI.');
