assert.match(html,/<dialog[^>]*aria-labelledby="detail-title"/);
assert.match(html,/Not an official or endorsed university website/);
assert.match(html,/<title>UCCS Resource Locator<\/title>/);
assert.ok(!html.includes('prototype-notice')&&!html.includes('resource-note')&&!html.includes('about-dialog'));
assert.match(html,/href="https:\/\/search\.uccs\.edu\/">RESOURCES\.search\.uccs\.edu/);
assert.match(html,/href="mailto:sheath3@uccs\.edu"/);
console.log('PASS Existing directory controls remain; the new title, linked search header, support email, and footer disclaimer are present.');
const logo=fs.readFileSync(path.join(root,'dist/assets/uccs-cu-lockup-reverse.svg'));
assert.equal(createHash('sha256').update(logo).digest('hex'),'b9ad3c84f8bce0f09631be4e27c37016ec87aff30a1b7299b23f3a1c72b1a9c0');
