import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import * as app from '../dist/app.js';
import {behaviorSnapshot} from './behavior-cases.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'dist/data/resources.json'),'utf8'));
const baseline=JSON.parse(fs.readFileSync(path.join(root,'docs/PHASE2_BEHAVIOR_BASELINE.json'),'utf8'));
