console.log('PASS Provider URL labels handle roots, paths, queries, missing values, and unsafe protocols.');
const html=fs.readFileSync(path.join(root,'dist/index.html'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'Duplicate static element IDs');
for(const id of ['resource-search','search-form','categories','location-select','cost-select','appointment-select','sort-select','official-check','resources','resource-dialog','saved-nav','mobile-filter-open','mobile-filter-close','starting-point','search-on-google','google-search-label'])assert.equal(ids.filter(x=>x===id).length,1,id);
