console.log('PASS Both search-page masthead/footer logo assets remain unmodified.');
const allPages=[];
for(let page=1;page<=15;page++)allPages.push(...app.paginateResources(data.resources,page).items.map(r=>r.id));
assert.deepEqual(allPages,data.resources.map(r=>r.id));
assert.equal(app.paginateResources(data.resources,15).items.length,10);
assert.equal(app.paginateResources(data.resources,999).page,15);
assert.equal(app.paginateResources([],15).items.length,0);
for(const current of [1,2,7,8,14,15]){const tokens=app.pageTokens(current,15);const numbers=tokens.filter(x=>typeof x==='number');assert.ok(numbers.includes(1)&&numbers.includes(15)&&numbers.includes(current));assert.equal(new Set(numbers).size,numbers.length);}
console.log('PASS Numbered paging covers all 178 entries once, including last/empty/out-of-range pages and page windows.');
